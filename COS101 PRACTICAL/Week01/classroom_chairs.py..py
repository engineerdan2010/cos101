# The program calculates the total number of chairs in the classroom.

rows = 6
chairs_per_row = 8

total_chairs = rows * chairs_per_row

print("Number of rows:", rows)
print("Chairs per row:", chairs_per_row)
print("Total number of chairs:", total_chairs)

#1. Problem statement = The problem is that a class has chairs arranged in roles and the
#goal is finding out the total number of chairs in the classroom

#2. Input, process, output =
#Input = Number of rows = 6; chairs per row = 8
#Process = Multiply the number of rows by the chairs per row
#Output = Number of rows, chairs per row, and the total number of chairs

#3. Numbered algorithm
#Start.
#Set the number of rows to 6.
#Set the number of chairs per row to 8.
#Calculate total chairs = rows × chairs per row.
#Display the number of rows.
#Display the number of chairs per row.
#Display the total number of chairs.
#Stop.

#4. Pseudocode
#START
#SET rows TO 6
#SET chairs_per_row TO 8
#SET total_chairs TO rows * chairs_per_row
#DISPLAY "Number of rows:", rows
